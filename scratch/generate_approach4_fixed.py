        "# =========================================================================\n",
        "# Step 4: Multi-Pass Blocker (Exact + Postal + Char 3-4 Gram + Word)\n",
        "# =========================================================================\n",
        "class MultiPassAdaptiveRetriever:\n",
        "    def __init__(self, country, target_records):\n",
        "        self.country = country\n",
        "        self.target_ids = [r['entity_id'] for r in target_records]\n",
        "        \n",
        "        # 1. Exact Anchor Indexes\n",
        "        self.exact_name_map = defaultdict(list)\n",
        "        self.exact_addr_map = defaultdict(list)\n",
        "        self.exact_joined_map = defaultdict(list)\n",
        "        self.postal_map = defaultdict(list)   # Dedicated Postal Blocking Index\n",
        "        \n",
        "        for idx, r in enumerate(target_records):\n",
        "            n = r['norm_name']\n",
        "            a = r['norm_addr']\n",
        "            j = r['joined_name']\n",
        "            p = r['postal']\n",
        "            if n and len(n) >= 3:\n",
        "                self.exact_name_map[n].append(idx)\n",
        "            if a and len(a) >= 6:\n",
        "                self.exact_addr_map[a].append(idx)\n",
        "            if j and len(j) >= 6:\n",
        "                self.exact_joined_map[j[:8]].append(idx)\n",
        "            if p and len(p) >= 4:\n",
        "                # Cap postal index list to avoid dense postals exploding candidate volume\n",
        "                if len(self.postal_map[p]) < 250:\n",
        "                    self.postal_map[p].append(idx)\n",
        "                \n",
        "        # 2. Multi-Pass Vectorizers (Char 3-4 Gram on Name + Word TF-IDF on Full)\n",
        "        t_names = [r['norm_name'] for r in target_records]\n",
        "        t_full = [r['norm_full'] for r in target_records]\n",
        "        \n",
        "        self.char_vec = TfidfVectorizer(\n",
        "            analyzer='char_wb', ngram_range=(3, 4), min_df=3, max_features=60000,\n",
        "            sublinear_tf=True, dtype=np.float32\n",
        "        )\n",
        "        self.t_char_mat = self.char_vec.fit_transform(t_names)\n",
        "        \n",
        "        self.word_vec = TfidfVectorizer(\n",
        "            analyzer='word', token_pattern=r'\\b\\w+\\b', min_df=3, max_df=0.25,\n",
        "            max_features=80000, sublinear_tf=True, dtype=np.float32\n",
        "        )\n",
        "        self.t_word_mat = self.word_vec.fit_transform(t_full)\n",
        "        \n",
        "        del t_names, t_full\n",
        "        gc.collect()\n",
        "\n",
        "    def retrieve(self, query_records, batch_size=500):\n",
        "        q_ids = [r['entity_id'] for r in query_records]\n",
        "        q_names = [r['norm_name'] for r in query_records]\n",
        "        q_full = [r['norm_full'] for r in query_records]\n",
        "        n_q = len(query_records)\n",
        "        \n",
        "        # candidate_scores: sid -> tid -> max_score\n",
        "        candidates_by_s1 = defaultdict(dict)\n",
        "        # blocker_votes: sid -> tid -> count_of_blockers_agreeing\n",
        "        blocker_votes = defaultdict(lambda: defaultdict(int))\n",
        "        has_exact_name = set()\n",
        "        \n",
        "        # Pass 1: Exact Anchors & Postal Blocking\n",
        "        for r in query_records:\n",
        "            sid = r['entity_id']\n",
        "            n, a, j, p = r['norm_name'], r['norm_addr'], r['joined_name'], r['postal']\n",
        "            \n",
        "            if n in self.exact_name_map:\n",
        "                for tidx in self.exact_name_map[n][:10]:\n",
        "                    tid = self.target_ids[tidx]\n",
        "                    candidates_by_s1[sid][tid] = 1.0\n",
        "                    blocker_votes[sid][tid] += 2\n",
        "                has_exact_name.add(sid)\n",
        "                \n",
        "            if a in self.exact_addr_map:\n",
        "                for tidx in self.exact_addr_map[a][:10]:\n",
        "                    tid = self.target_ids[tidx]\n",
        "                    candidates_by_s1[sid][tid] = max(candidates_by_s1[sid].get(tid, 0.0), 0.95)\n",
        "                    blocker_votes[sid][tid] += 2\n",
        "                    \n",
        "            if j and len(j) >= 6:\n",
        "                jk = j[:8]\n",
        "                if jk in self.exact_joined_map:\n",
        "                    for tidx in self.exact_joined_map[jk][:8]:\n",
        "                        tid = self.target_ids[tidx]\n",
        "                        candidates_by_s1[sid][tid] = max(candidates_by_s1[sid].get(tid, 0.0), 0.90)\n",
        "                        blocker_votes[sid][tid] += 1\n",
        "                        \n",
        "            # Dedicated Postal index (only for queries with valid postal and non-empty name)\n",
        "            if p and len(p) >= 4 and p in self.postal_map and len(n) >= 3:\n",
        "                for tidx in self.postal_map[p][:25]:\n",
        "                    tid = self.target_ids[tidx]\n",
        "                    candidates_by_s1[sid][tid] = max(candidates_by_s1[sid].get(tid, 0.0), 0.50)\n",
        "                    blocker_votes[sid][tid] += 1\n",
        "                    \n",
        "        # Pass 2: Batched Word TF-IDF + Char N-Gram Dot Products\n",
        "        for s_idx in range(0, n_q, batch_size):\n",
        "            e_idx = min(s_idx + batch_size, n_q)\n",
        "            b_sids = q_ids[s_idx:e_idx]\n",
        "            \n",
        "            # Word dot product on full string\n",
        "            q_w_mat = self.word_vec.transform(q_full[s_idx:e_idx])\n",
        "            sim_w = q_w_mat.dot(self.t_word_mat.T)\n",
        "            \n",
        "            # Char n-gram dot product on name\n",
        "            q_c_mat = self.char_vec.transform(q_names[s_idx:e_idx])\n",
        "            sim_c = q_c_mat.dot(self.t_char_mat.T)\n",
        "            \n",
        "            for i, sid in enumerate(b_sids):\n",
        "                st_w, en_w = sim_w.indptr[i], sim_w.indptr[i+1]\n",
        "                if st_w != en_w:\n",
        "                    t_idx_w = sim_w.indices[st_w:en_w]\n",
        "                    sc_w = sim_w.data[st_w:en_w]\n",
        "                    if len(sc_w) > 30:\n",
        "                        part = np.argpartition(-sc_w, 30)[:30]\n",
        "                        t_idx_w, sc_w = t_idx_w[part], sc_w[part]\n",
        "                    for ti, score in zip(t_idx_w, sc_w):\n",
        "                        if score > 0.08:\n",
        "                            tid = self.target_ids[ti]\n",
        "                            candidates_by_s1[sid][tid] = max(candidates_by_s1[sid].get(tid, 0.0), float(score))\n",
        "                            blocker_votes[sid][tid] += 1\n",
        "                            \n",
        "                st_c, en_c = sim_c.indptr[i], sim_c.indptr[i+1]\n",
        "                if st_c != en_c:\n",
        "                    t_idx_c = sim_c.indices[st_c:en_c]\n",
        "                    sc_c = sim_c.data[st_c:en_c]\n",
        "                    if len(sc_c) > 25:\n",
        "                        part = np.argpartition(-sc_c, 25)[:25]\n",
        "                        t_idx_c, sc_c = t_idx_c[part], sc_c[part]\n",
        "                    for ti, score in zip(t_idx_c, sc_c):\n",
        "                        if score > 0.18:\n",
        "                            tid = self.target_ids[ti]\n",
        "                            candidates_by_s1[sid][tid] = max(candidates_by_s1[sid].get(tid, 0.0), float(score))\n",
        "                            blocker_votes[sid][tid] += 1\n",
        "                            \n",
        "        # Pass 3: True Adaptive K Allocation based on Multi-Blocker Diagnostics\n",
        "        final_cands = {}\n",
        "        for sid, cands in candidates_by_s1.items():\n",
        "            if not cands:\n",
        "                final_cands[sid] = []\n",
        "                continue\n",
        "                \n",
        "            # Sort candidates by combined score + blocker agreement bonus\n",
        "            scored = []\n",
        "            for tid, sc in cands.items():\n",
        "                votes = blocker_votes[sid].get(tid, 1)\n",
        "                # Priority ranking: score + 0.1 * min(3, votes)\n",
        "                priority = sc + 0.10 * min(3, votes)\n",
        "                scored.append((tid, sc, priority))\n",
        "            scored.sort(key=lambda x: x[2], reverse=True)\n",
        "            \n",
        "            top_score = scored[0][1]\n",
        "            top_gap = (scored[0][2] - scored[1][2]) if len(scored) > 1 else 1.0\n",
        "            \n",
        "            # Diagnostic Adaptive K Decision:\n",
        "            # 1. Clear Exact Match with large score gap: K = 6\n",
        "            # 2. Strong multi-blocker consensus: K = 12\n",
        "            # 3. High ambiguity (weak overlap, tiny gap): expand K up to 40\n",
        "            if sid in has_exact_name and top_gap >= 0.35:\n",
        "                k_budget = 6\n",
        "            elif top_score >= 0.80 and top_gap >= 0.20:\n",
        "                k_budget = 12\n",
        "            elif top_score >= 0.50:\n",
        "                k_budget = 22\n",
        "            else:\n",
        "                k_budget = 40\n",
        "                \n",
        "            final_cands[sid] = [(tid, sc) for tid, sc, _ in scored[:k_budget]]\n",
        "            \n",
        "        return final_cands\n",
        "\n",
