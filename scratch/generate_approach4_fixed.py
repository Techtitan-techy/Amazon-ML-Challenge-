        "RE_LEGAL = re.compile(r'\\b(' + '|'.join(re.escape(s) for s in LEGAL_SUFFIXES) + r')\\b', re.IGNORECASE)\n",
        "\n",
        "RE_IN_PIN = re.compile(r'\\b([1-9][0-9]{2}\\s?[0-9]{3})\\b')\n",
        "RE_US_ZIP = re.compile(r'\\b([0-9]{5}(?:-[0-9]{4})?)\\b')\n",
